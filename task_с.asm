
.data
array: .space 104    # 26 элементов по 4 байта

.text
.globl main

main:
    la t0, array     # адрес начала массива
    li t1, 0         # количество введённых элементов
    li t2, 26        # максимальное количество элементов

read_loop:
    # Проверяем, заполнен ли массив
    bge t1, t2, finish

    # Считываем целое число
    li a7, 5
    ecall

    # Если введён ноль, завершаем ввод
    beq a0, zero, finish

    # Сохраняем число в массив
    sw a0, 0(t0)

    # Переходим к следующему элементу
    addi t0, t0, 4
    addi t1, t1, 1

    j read_loop

finish:
    # Выводим количество сохранённых элементов
    mv a0, t1
    li a7, 1
    ecall

    # Завершаем программу
    li a7, 10
    ecall